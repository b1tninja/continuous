#!/usr/bin/env node
/**
 * Generate core/util/specialPurpose.generated.ts from the IANA Special-Purpose
 * Address Registries (RFC 6890, BCP 153, as updated by RFC 8190).
 *
 * The CSVs are kept beside the output in core/util/iana/ so the table can be
 * regenerated without a network request and a test can check that the
 * committed table is exactly what these files produce. To refresh:
 *
 *   curl -o core/util/iana/iana-ipv4-special-registry-1.csv \
 *     https://www.iana.org/assignments/iana-ipv4-special-registry/iana-ipv4-special-registry-1.csv
 *   curl -o core/util/iana/iana-ipv6-special-registry-1.csv \
 *     https://www.iana.org/assignments/iana-ipv6-special-registry/iana-ipv6-special-registry-1.csv
 *   node core/scripts/generate-special-purpose.mjs <registry updated date>
 *   npx prettier --write core/util/specialPurpose.generated.ts
 *
 * The date is the registry's own "Last Updated" value (the <updated> element
 * of the XML form); without one the date already in the generated file is kept.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const IANA_DIR = path.join(here, "..", "util", "iana");
export const OUTPUT = path.join(
  here,
  "..",
  "util",
  "specialPurpose.generated.ts",
);
export const V4_CSV = "iana-ipv4-special-registry-1.csv";
export const V6_CSV = "iana-ipv6-special-registry-1.csv";

/** Split CSV text into rows of fields (RFC 4180 quoting). */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        quoted = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += c;
    }
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((f) => f.trim() !== ""));
}

/** "False [1]" -> false, "True" -> true, "N/A [2]" or "" -> null. */
function boolCell(value) {
  const v = value.replace(/\[\d+\]/g, "").trim();
  if (v === "True") return true;
  if (v === "False") return false;
  return null;
}

/**
 * Registry rows as blocks. A cell may hold several blocks
 * ("192.0.0.170/32, 192.0.0.171/32") and footnote marks ("192.0.0.0/24 [2]").
 */
export function parseRegistry(text) {
  const [header, ...rows] = parseCsv(text);
  const col = (name) => {
    const i = header.indexOf(name);
    if (i === -1) throw new Error(`Registry has no "${name}" column`);
    return i;
  };
  const block = col("Address Block");
  const name = col("Name");
  const rfc = col("RFC");
  const reachable = col("Globally Reachable");
  const terminated = col("Termination Date");
  const out = [];
  for (const row of rows) {
    const blocks = row[block]
      .replace(/\[\d+\]/g, "")
      .split(",")
      .map((b) => b.trim())
      .filter(Boolean);
    const end = row[terminated].trim();
    for (const prefix of blocks) {
      out.push({
        prefix,
        name: row[name].replace(/^"|"$/g, "").trim(),
        rfc: row[rfc].replace(/\s+/g, " ").trim(),
        globallyReachable: boolCell(row[reachable] ?? ""),
        ...(end && end !== "N/A" ? { terminated: end } : {}),
      });
    }
  }
  return out;
}

export function render(v4, v6, updated) {
  const lines = (entries) =>
    entries.map((e) => `  ${JSON.stringify(e)},`).join("\n");
  return `// Generated by core/scripts/generate-special-purpose.mjs from the IANA
// IPv4 and IPv6 Special-Purpose Address Registries (RFC 6890, BCP 153, as
// updated by RFC 8190). Do not edit by hand: refresh the CSVs in
// core/util/iana/ and run the script. specialPurpose.vitest.ts checks that
// these tables are exactly what those CSVs produce.

export interface SpecialPurposeBlock {
  /** CIDR prefix as the registry writes it */
  prefix: string;
  name: string;
  rfc: string;
  /**
   * The registry's "Globally Reachable" column (RFC 8190 section 2.1); null
   * where it says N/A or nothing (a terminated entry).
   */
  globallyReachable: boolean | null;
  /** Termination date of a deprecated entry */
  terminated?: string;
}

/** The registries' "Last Updated" date for the CSVs this was generated from. */
export const SPECIAL_PURPOSE_REGISTRY_UPDATED = ${JSON.stringify(updated)};

export const IPV4_SPECIAL_PURPOSE: readonly SpecialPurposeBlock[] = [
${lines(v4)}
];

export const IPV6_SPECIAL_PURPOSE: readonly SpecialPurposeBlock[] = [
${lines(v6)}
];
`;
}

export function generate(updated) {
  const read = (f) => fs.readFileSync(path.join(IANA_DIR, f), "utf8");
  return render(
    parseRegistry(read(V4_CSV)),
    parseRegistry(read(V6_CSV)),
    updated,
  );
}

/** The date recorded in the current generated file, if there is one. */
export function currentUpdatedDate() {
  try {
    const m = /SPECIAL_PURPOSE_REGISTRY_UPDATED = "([^"]+)"/.exec(
      fs.readFileSync(OUTPUT, "utf8"),
    );
    return m?.[1];
  } catch {
    return undefined;
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const updated = process.argv[2] ?? currentUpdatedDate();
  if (!updated) {
    console.error("Pass the registry's Last Updated date (YYYY-MM-DD).");
    process.exit(1);
  }
  fs.writeFileSync(OUTPUT, generate(updated));
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
}
